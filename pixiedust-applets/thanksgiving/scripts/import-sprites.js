// Converts CC0 sprite PNGs in assets/ into palette-indexed text sprites in
// lib/, with a brightness lift so dark browns survive the renderer's gamma 2.8.
//
//   node scripts/import-sprites.js
const fs = require("fs");
const path = require("path");
const { createCanvas, loadImage } = require("canvas");

const LIFT = 1.5; // channel' = channel^(1/LIFT)
const KEYS = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789#$%&*+=?@";
const SETS = [
  { src: "assets/henry-food", out: "lib/henryFood.ts", credit: "Free Pixel Food by Henry Software" },
  { src: "assets/kami-pumpkins", out: "lib/kamiPumpkins.ts", credit: "Pixel Pumpkins by Kami" },
];

const hex = (v) => v.toString(16).padStart(2, "0");

async function convert({ src, out, credit }) {
  const SRC = path.join(__dirname, "..", src);
  const OUT = path.join(__dirname, "..", out);
  const names = fs.readdirSync(SRC).filter((f) => f.endsWith(".png")).sort();
  let ts = `// Generated by scripts/import-sprites.js from ${src} (CC0,\n// ${credit}). Do not edit by hand.\nimport { Sprite } from "./sprite";\n\n`;
  for (const file of names) {
    const img = await loadImage(path.join(SRC, file));
    const c = createCanvas(img.width, img.height);
    const ctx = c.getContext("2d");
    ctx.drawImage(img, 0, 0);
    const { data, width, height } = ctx.getImageData(0, 0, img.width, img.height);
    const legend = new Map();
    const rows = [];
    for (let y = 0; y < height; y++) {
      let row = "";
      for (let x = 0; x < width; x++) {
        const i = (y * width + x) * 4;
        if (data[i + 3] < 128) { row += "."; continue; }
        const lift = (v) => Math.round(Math.pow(v / 255, 1 / LIFT) * 255);
        const color = `#${hex(lift(data[i]))}${hex(lift(data[i + 1]))}${hex(lift(data[i + 2]))}`;
        if (!legend.has(color)) {
          if (legend.size >= KEYS.length) throw new Error(`${file}: too many colors`);
          legend.set(color, KEYS[legend.size]);
        }
        row += legend.get(color);
      }
      rows.push(row);
    }
    // Trim fully transparent rows/columns so sprites sit on the table
    while (rows.length && /^\.*$/.test(rows[rows.length - 1])) rows.pop();
    while (rows.length && /^\.*$/.test(rows[0])) rows.shift();
    const left = Math.min(...rows.map((r) => r.search(/[^.]/)).filter((i) => i >= 0));
    const right = Math.max(...rows.map((r) => r.replace(/\.+$/, "").length));
    const trimmed = rows.map((r) => r.slice(left, right));
    const name = path.basename(file, ".png");
    const leg = [...legend].map(([c, k]) => `"${k}": "${c}"`).join(", ");
    ts += `export const ${name.toUpperCase()}: Sprite = {\n  legend: { ${leg} },\n  rows: [\n${trimmed.map((r) => `    ${JSON.stringify(r)},`).join("\n")}\n  ],\n};\n\n`;
  }
  fs.writeFileSync(OUT, ts);
  console.log(`wrote ${names.length} sprites to ${out}`);
}

(async () => {
  for (const set of SETS) await convert(set);
})();
